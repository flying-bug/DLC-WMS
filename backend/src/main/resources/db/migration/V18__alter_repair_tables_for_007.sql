    ADD COLUMN under_warranty BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN repair_warranty_end_date DATE NULL,
    ADD COLUMN invoice_method VARCHAR(30) NOT NULL DEFAULT 'after_repair',
    ADD COLUMN approved_by BIGINT UNSIGNED NULL,
    ADD COLUMN created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    ADD COLUMN updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    MODIFY COLUMN serial_number_id BIGINT UNSIGNED NULL,
    MODIFY COLUMN warranty_id BIGINT UNSIGNED NULL;

CREATE TABLE REPAIR_LINES (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    repair_id BIGINT UNSIGNED NOT NULL,
    component_variant_id BIGINT UNSIGNED NOT NULL,
    action_type VARCHAR(20) NOT NULL,
    quantity DECIMAL(15,4) NOT NULL,
    unit_price DECIMAL(15,2) NOT NULL DEFAULT 0.00,
    is_free_warranty BOOLEAN NOT NULL DEFAULT FALSE,
    serial_number_id BIGINT UNSIGNED NULL,
    note TEXT,
    CONSTRAINT fk_repair_lines_repair FOREIGN KEY (repair_id) REFERENCES REPAIRS(id) ON DELETE CASCADE
);

CREATE TABLE REPAIR_FEES (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    repair_id BIGINT UNSIGNED NOT NULL,
    fee_name VARCHAR(255) NOT NULL,
    fee_amount DECIMAL(15,2) NOT NULL DEFAULT 0.00,
    is_free_warranty BOOLEAN NOT NULL DEFAULT FALSE,
    note TEXT,
    CONSTRAINT fk_repair_fees_repair FOREIGN KEY (repair_id) REFERENCES REPAIRS(id) ON DELETE CASCADE
);
